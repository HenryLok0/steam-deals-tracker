export function detectCurrency() {
  const saved = localStorage.getItem("steam-deals-currency");
  if (saved && SUPPORTED_CURRENCIES.includes(saved)) {
    return saved;
  }
  return "USD";
}

export function detectLanguage() {
  const saved = localStorage.getItem("steam-free-games-lang");
  if (saved && SUPPORTED_LANGUAGES.includes(saved)) {
    return saved;
  }

  const browserLang = navigator.language || "en";
  if (browserLang.startsWith("zh-CN") || browserLang === "zh-Hans") return "zh-Hans";
  if (browserLang.startsWith("zh")) return "zh-Hant";
  if (browserLang.startsWith("ja")) return "ja";
  if (browserLang.startsWith("ko")) return "ko";
  return "en";
}

export function t(lang, key, vars = {}) {
  const table = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const template = table[key] || TRANSLATIONS.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}
